/**
 * buildBundles.ts -- generate the human reviewer packets for the
 * california-law-v1 benchmark (spec CALC-KIMI-K3-GPT56-JUDGE-001, batch B8).
 *
 * WHAT THIS DOES
 *   Reads the canonical dataset and emits one self-contained review packet per
 *   task, plus an index, a machine-readable bundle file, and a manifest. The
 *   packets are what the two independent non-attorney reviewers read; the
 *   machine-readable bundle file is what datasetTools/makeAttestation.ts reads
 *   to emit hash-bound BenchmarkAttestation records. Nothing here writes an
 *   attestation, and nothing here judges candidate model output.
 *
 * INPUT FILES (absolute paths)
 *   /Users/arjundivecha/Dropbox/AAA Backup/A Working/California-Law-Chatbot/evals/kimi-k3/datasets/california-law-v1/tasks.jsonl
 *   /Users/arjundivecha/Dropbox/AAA Backup/A Working/California-Law-Chatbot/evals/kimi-k3/datasets/california-law-v1/sources.jsonl
 *   /Users/arjundivecha/Dropbox/AAA Backup/A Working/California-Law-Chatbot/evals/kimi-k3/datasets/california-law-v1/provenance/b8a-officiality-audit.json
 *
 * OUTPUT FILES (absolute paths, all under
 *   /Users/arjundivecha/Dropbox/AAA Backup/A Working/California-Law-Chatbot/evals/kimi-k3/review-bundles/)
 *   manifest.json          -- dataset hash, counts, source-caveat lists
 *   bundles.jsonl          -- one machine-readable bundle row per task
 *   index.md               -- reviewer index table (all 120 tasks, flags visible)
 *   tasks/<task-id>.md     -- 120 human review packets
 *   (README.md is hand-written and is NOT regenerated by this script)
 *
 * USAGE
 *   ./node_modules/.bin/tsx "evals/kimi-k3/review-bundles/buildBundles.ts"
 *
 * NOTES
 *   Deterministic: no Date.now(), no Math.random(), no network. The
 *   generated_from_dataset_hash in manifest.json is the same
 *   benchmarkDatasetHash() value that live-mode attestation binding uses, so a
 *   packet whose manifest hash no longer matches the dataset is stale by
 *   construction and its attestations will be rejected.
 */
import { readFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { atomicWriteFileSync } from '../journal.js';
import {
  benchmarkDatasetHash,
  benchmarkPropositionHashes,
  benchmarkSourceHashes,
} from '../integrity.js';
import type { EvalTask } from '../types.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const DATASET = join(HERE, '..', 'datasets', 'california-law-v1');
const TASKS = join(DATASET, 'tasks.jsonl');
const AUDIT = join(DATASET, 'provenance', 'b8a-officiality-audit.json');
const TASKS_DIR = join(HERE, 'tasks');

/** Reviewer reason codes. APPROVE may carry zero codes. */
export const REVIEW_REASON_CODES = {
  APPROVE: [
    'ENTAILED_AND_SELF_CONTAINED',
    'APPROVED_WITH_AGGREGATOR_CAVEAT_NOTED',
  ],
  REJECT: [
    'UNSUPPORTED_PROPOSITION',
    'CRITERION_REQUIRES_OUTSIDE_LEGAL_MEMORY',
    'STALE_EFFECTIVE_DATE',
    'AMBIGUOUS_AUTHORITY_STATUS',
    'FAILED_SOURCE_HASH',
    'EXCERPT_NOT_VERBATIM',
    'CRITERION_PROPOSITION_MISMATCH',
    'AGGREGATOR_SOURCE_NOT_ACCEPTABLE',
    'ARCHIVED_SOURCE_NOT_ACCEPTABLE',
    'PROMPT_CONTAINS_NONPUBLIC_MATERIAL',
  ],
} as const;

function loadTasks(): EvalTask[] {
  return readFileSync(TASKS, 'utf8')
    .split('\n')
    .filter((line) => line.trim().length > 0)
    .map((line) => JSON.parse(line) as EvalTask);
}

function words(value: string): number {
  return value.trim().length === 0 ? 0 : value.trim().split(/\s+/u).length;
}

function clip(value: string, limit: number): string {
  const normalized = value.replace(/\r/gu, '');
  if (normalized.length <= limit) return normalized;
  return `${normalized.slice(0, limit).trimEnd()}\n\n[... truncated for review: `
    + `${words(normalized)} words total in the original prompt ...]`;
}

function fence(value: string): string {
  const marker = value.includes('```') ? '~~~~' : '```';
  return `${marker}text\n${value}\n${marker}`;
}

interface AuditRecord {
  source_id: string;
  case?: string;
  disposition: string;
  new_canonical_url?: string | null;
  old_canonical_url?: string;
  notes?: string;
}

function main(): void {
  const tasks = loadTasks();
  const datasetHash = benchmarkDatasetHash(tasks);
  const audit = JSON.parse(readFileSync(AUDIT, 'utf8')) as {
    records: AuditRecord[];
  };
  const noOfficialHosting = new Map<string, AuditRecord>(
    audit.records
      .filter((record) => record.disposition === 'NO_OFFICIAL_HOSTING')
      .map((record) => [record.source_id, record]),
  );
  const waybackOnly = 'CIT-REAL-16';

  if (existsSync(TASKS_DIR)) rmSync(TASKS_DIR, { recursive: true });
  mkdirSync(TASKS_DIR, { recursive: true });

  const bundleRows: string[] = [];
  const indexRows: string[] = [];
  const flaggedTasks: string[] = [];

  for (const task of tasks) {
    const propositionHashes = benchmarkPropositionHashes(task);
    const sourceHashes = benchmarkSourceHashes(task);
    const propositionById = new Map(
      task.provenance.map((record) => [record.proposition_id, record]),
    );
    const evidenceById = new Map(
      task.evidence.map((record) => [record.source_id, record]),
    );
    const caveats = task.evidence
      .filter((record) => noOfficialHosting.has(record.source_id))
      .map((record) => record.source_id);
    const needsPolicyCall = task.evidence.some(
      (record) => record.source_id === waybackOnly,
    );
    if (caveats.length > 0 || needsPolicyCall) flaggedTasks.push(task.id);

    /* ---------------------------------------------------------------- md */
    const lines: string[] = [];
    lines.push(`# Review packet — \`${task.id}\``);
    lines.push('');
    lines.push(
      '> Validate the BENCHMARK, not any model answer. For every material '
      + 'criterion below, ask only: **is this criterion entailed by the '
      + 'excerpt printed underneath it, using nothing but the words on this '
      + 'page?** If you need outside legal knowledge to agree, that is a '
      + 'REJECT. See ../README.md.',
    );
    lines.push('');
    lines.push('## 1. Identity and hashes');
    lines.push('');
    lines.push('| field | value |');
    lines.push('| --- | --- |');
    lines.push(`| task_id | \`${task.id}\` |`);
    lines.push(`| category | ${task.category} |`);
    lines.push(`| workflow | ${task.workflow} |`);
    lines.push(`| track | ${task.track} |`);
    lines.push(`| data_class | ${task.data_class} |`);
    lines.push(`| dataset_hash | \`${datasetHash}\` |`);
    lines.push(
      `| task_content_sha256 | \`${task.task_content_sha256 ?? '(absent)'}\` |`,
    );
    lines.push(
      `| proposition_hashes | ${propositionHashes.length} — `
      + `\`${propositionHashes.map((hash) => hash.slice(0, 12)).join('`, `')}\` |`,
    );
    lines.push(
      `| source_hashes | ${sourceHashes.length} — `
      + `\`${sourceHashes.map((hash) => hash.slice(0, 12)).join('`, `')}\` |`,
    );
    lines.push('');
    if (caveats.length > 0 || needsPolicyCall) {
      lines.push('## ⚠ Source caveats you must weigh');
      lines.push('');
      for (const sourceId of caveats) {
        const record = noOfficialHosting.get(sourceId) as AuditRecord;
        lines.push(
          `- **\`${sourceId}\`${record.case ? ` (${record.case})` : ''} — `
          + 'NO_OFFICIAL_HOSTING.** The excerpt is hosted by an aggregator, '
          + 'not by an official California court site. The B8a audit tried the '
          + 'courts.ca.gov opinion archive, the published-opinion URL scheme, '
          + 'courts.ca.gov site search, and the Wayback Machine and found no '
          + 'live official copy (these are mostly pre-2015 Supreme Court and '
          + 'pre-1993 Court of Appeal opinions that predate the electronic '
          + 'archive). Decide whether you are willing to attest that the '
          + 'quoted words are the court’s words on this basis.',
        );
      }
      if (needsPolicyCall) {
        lines.push(
          '- **`CIT-REAL-16` (Sargon Enterprises v. USC) — WAYBACK-ONLY, '
          + 'POLICY DECISION REQUIRED.** The official courts.ca.gov PDF 404s '
          + 'today. A Wayback Machine capture (2014-04-15) of the '
          + 'once-live official page verified the stored quote verbatim, but '
          + 'the record was deliberately NOT re-anchored to a web.archive.org '
          + 'URL. **Do not silently approve or reject this on your own '
          + 'judgment: record your view and flag it, so the benchmark owner '
          + 'can set one policy for the whole dataset** — either "an archived '
          + 'capture of an official page may serve as canonical_url" or "it '
          + 'may not, and this task is excluded and replaced".',
        );
      }
      lines.push('');
    }
    lines.push('## 2. Prompt (what the model is asked)');
    lines.push('');
    lines.push(fence(clip(task.prompt, 2400)));
    lines.push('');
    if (task.turns.length > 1) {
      lines.push(
        `### Conversation (${task.turns.length} turns; only the final user `
        + 'turn is graded)',
      );
      lines.push('');
      task.turns.forEach((turn, index) => {
        const graded = index === task.turns.length - 1 ? ' **(graded)**' : '';
        lines.push(`**Turn ${index + 1} — ${turn.role}**${graded}`);
        lines.push('');
        lines.push(fence(clip(turn.content, 1200)));
        lines.push('');
      });
    }
    lines.push('## 3. Material criteria and their propositions');
    lines.push('');
    const material = task.criteria.filter((criterion) => criterion.material);
    const nonMaterial = task.criteria.filter(
      (criterion) => !criterion.material,
    );
    material.forEach((criterion, index) => {
      lines.push(`### C${index + 1}. \`${criterion.criterion_id}\``);
      lines.push('');
      lines.push(`**Criterion:** ${criterion.description}`);
      lines.push('');
      for (const propositionId of criterion.proposition_ids) {
        const proposition = propositionById.get(propositionId);
        if (!proposition) {
          lines.push(`- ⚠ MISSING PROPOSITION \`${propositionId}\``);
          continue;
        }
        const evidence = evidenceById.get(proposition.source_id);
        lines.push(`#### Proposition \`${proposition.proposition_id}\``);
        lines.push('');
        lines.push(`> ${proposition.proposition}`);
        lines.push('');
        lines.push('**Verbatim authoritative excerpt relied on:**');
        lines.push('');
        lines.push(fence(proposition.authoritative_excerpt));
        lines.push('');
        lines.push('| source field | value |');
        lines.push('| --- | --- |');
        lines.push(`| source_id | \`${proposition.source_id}\` |`);
        lines.push(`| locator | ${proposition.locator} |`);
        lines.push(`| jurisdiction | ${proposition.jurisdiction} |`);
        lines.push(`| authority status | ${proposition.authority_status} |`);
        lines.push(`| effective date | ${proposition.effective_date} |`);
        lines.push(`| retrieved at | ${proposition.retrieved_at} |`);
        lines.push(
          `| canonical URL | <${proposition.canonical_url}> |`,
        );
        lines.push(`| source sha256 | \`${proposition.source_sha256}\` |`);
        if (noOfficialHosting.has(proposition.source_id)) {
          lines.push('| ⚠ officiality | AGGREGATOR-HOSTED (NO_OFFICIAL_HOSTING) |');
        }
        lines.push('');
        if (evidence) {
          lines.push(
            '<details><summary>Full source excerpt as stored in the registry '
            + `(${words(evidence.authoritative_excerpt)} words) — the quoted `
            + 'proposition excerpt above must appear inside it verbatim'
            + '</summary>',
          );
          lines.push('');
          lines.push(fence(clip(evidence.authoritative_excerpt, 6000)));
          lines.push('');
          lines.push('</details>');
          lines.push('');
        }
      }
    });
    if (nonMaterial.length > 0) {
      lines.push('### Non-material criteria (not attested, listed for context)');
      lines.push('');
      for (const criterion of nonMaterial) {
        lines.push(`- \`${criterion.criterion_id}\` — ${criterion.description}`);
      }
      lines.push('');
    }
    lines.push('## 4. Deterministic assertions (machine-checked, FYI)');
    lines.push('');
    if (task.deterministic_assertions.length === 0) {
      lines.push('_None._');
    } else {
      lines.push('| assertion_id | kind | expected | hard failure code |');
      lines.push('| --- | --- | --- | --- |');
      for (const assertion of task.deterministic_assertions) {
        const expected = Array.isArray(assertion.expected)
          ? assertion.expected.join(' / ')
          : String(assertion.expected);
        lines.push(
          `| \`${assertion.assertion_id}\` | ${assertion.kind} | `
          + `${expected.replace(/\|/gu, '\\|')} | `
          + `${assertion.hard_failure_code ?? '—'} |`,
        );
      }
    }
    lines.push('');
    lines.push('## 5. Your decision');
    lines.push('');
    lines.push('```');
    lines.push(`task_id:      ${task.id}`);
    lines.push('reviewer_id:  ______________________   (your opaque id, e.g. REV-A)');
    lines.push('reviewed_at:  ____-__-__T__:__:__Z');
    lines.push('decision:     [ ] APPROVE     [ ] REJECT');
    lines.push('reason_codes: ______________________________________');
    lines.push('```');
    lines.push('');
    lines.push('**APPROVE reason codes (0 or more):**');
    lines.push('');
    for (const code of REVIEW_REASON_CODES.APPROVE) {
      lines.push(`- \`${code}\``);
    }
    lines.push('');
    lines.push('**REJECT reason codes (at least one required):**');
    lines.push('');
    for (const code of REVIEW_REASON_CODES.REJECT) {
      lines.push(`- \`${code}\``);
    }
    lines.push('');
    lines.push('Then emit the machine-readable record:');
    lines.push('');
    lines.push('```bash');
    lines.push(
      './node_modules/.bin/tsx evals/kimi-k3/datasetTools/makeAttestation.ts \\',
    );
    lines.push(`  --task ${task.id} --reviewer REV-A --decision APPROVE \\`);
    lines.push('  --reviewed-at 2026-07-28T00:00:00Z \\');
    lines.push('  --reason ENTAILED_AND_SELF_CONTAINED \\');
    lines.push('  --out ~/benchmark-attestations/california-law-v1.jsonl');
    lines.push('```');
    lines.push('');
    lines.push(
      '_Attestation files live OUTSIDE this repository. Never commit them._',
    );
    lines.push('');

    atomicWriteFileSync(
      join(TASKS_DIR, `${task.id}.md`),
      `${lines.join('\n')}`,
      { mode: 0o644 },
    );

    /* ------------------------------------------------------------ bundle */
    bundleRows.push(JSON.stringify({
      task_id: task.id,
      category: task.category,
      workflow: task.workflow,
      track: task.track,
      data_class: task.data_class,
      dataset_hash: datasetHash,
      task_content_sha256: task.task_content_sha256,
      proposition_hashes: propositionHashes,
      source_hashes: sourceHashes,
      material_criteria: material.length,
      propositions: task.provenance.length,
      evidence_source_ids: task.evidence.map((record) => record.source_id),
      prompt_words: words(task.prompt),
      turns: task.turns.length,
      aggregator_caveat_source_ids: caveats,
      requires_archived_source_policy_decision: needsPolicyCall,
      packet: `tasks/${task.id}.md`,
    }));

    indexRows.push(
      `| [\`${task.id}\`](tasks/${task.id}.md) | ${task.category} | `
      + `${material.length} | ${task.provenance.length} | `
      + `${task.evidence.length} | ${words(task.prompt)} | `
      + `${caveats.length > 0 ? `⚠ ${caveats.join(', ')}` : '—'} | `
      + `${needsPolicyCall ? '⚠ POLICY' : '—'} |`,
    );
  }

  /* ----------------------------------------------------------- index.md */
  const index: string[] = [];
  index.push('# california-law-v1 — reviewer packet index');
  index.push('');
  index.push(`Dataset hash: \`${datasetHash}\``);
  index.push('');
  index.push(
    `${tasks.length} tasks. ${flaggedTasks.length} carry a source caveat you `
    + 'must weigh (see README.md § "Two things that are not clean").',
  );
  index.push('');
  index.push('Read [README.md](README.md) first.');
  index.push('');
  index.push(
    '| task | category | material criteria | propositions | sources | '
    + 'prompt words | aggregator caveat | archived-source policy |',
  );
  index.push('| --- | --- | --- | --- | --- | --- | --- | --- |');
  index.push(...indexRows);
  index.push('');
  atomicWriteFileSync(join(HERE, 'index.md'), `${index.join('\n')}\n`, {
    mode: 0o644,
  });

  atomicWriteFileSync(
    join(HERE, 'bundles.jsonl'),
    `${bundleRows.join('\n')}\n`,
    { mode: 0o644 },
  );

  const manifest = {
    bundle_kind: 'benchmark_reviewer_packets',
    dataset: 'california-law-v1',
    spec_ref: 'specs/CALC-KIMI-K3-GPT56-JUDGE-001.spec.md',
    generated_from_dataset_hash: datasetHash,
    task_count: tasks.length,
    packet_count: tasks.length,
    files: {
      readme: 'README.md',
      index: 'index.md',
      machine_readable_bundles: 'bundles.jsonl',
      packets_dir: 'tasks/',
      attestation_tool: '../datasetTools/makeAttestation.ts',
    },
    reviewers_required_per_task: 2,
    attestations_are_external: true,
    reason_codes: REVIEW_REASON_CODES,
    aggregator_caveat_source_ids: [...noOfficialHosting.keys()].sort(),
    archived_source_policy_decision_source_id: waybackOnly,
    tasks_with_any_caveat: flaggedTasks.sort(),
  };
  atomicWriteFileSync(
    join(HERE, 'manifest.json'),
    `${JSON.stringify(manifest, null, 1)}\n`,
    { mode: 0o644 },
  );

  console.log(JSON.stringify({
    dataset_hash: datasetHash,
    packets: tasks.length,
    tasks_with_caveat: flaggedTasks.length,
    aggregator_caveat_source_ids: [...noOfficialHosting.keys()].sort(),
  }, null, 1));
}

main();
